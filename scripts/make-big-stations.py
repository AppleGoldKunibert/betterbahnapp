#!/usr/bin/env python3
"""Builds BetterBahnKit's list of big stations for the collection ("Große Bahnhöfe", #384): every DB station
in price class ("Preisklasse") 1 or 2, from DB InfraGO's "OpenStation NeTEx" (Deutsche Bahn AG, CC0 1.0;
https://mobilithek.info/offers/879076212433727488, key DBINFRAGO_PRICE_CATEGORY). Stations are keyed by
their DHID as `scripts/make-station-names.py` writes it, and named as in StationNames.json (DB's RIS name),
so run it after that script.

    curl -L --compressed -o netex.xml https://bahnhof.de/daten/netex
    python3 scripts/make-big-stations.py netex.xml
"""
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent / "Packages/BetterBahnKit/Sources/BetterBahnKit"
NAMES = KIT / "Resources/StationNames.json"
OUT = KIT / "Models/BigStations.swift"
NETEX = "{http://www.netex.org.uk/netex}"
PRICE_CLASSES = {"1", "2"}


def dhid_key(dhid):
    """Same as make-station-names.py: "de:07111:010001" → "de:07111:10001"."""
    parts = dhid.split(":")
    if len(parts) < 3 or parts[0] != "de" or not parts[2].isdigit():
        return ""
    return f"de:{parts[1]}:{int(parts[2])}"


def big_stations(netex_path):
    """(DHID key, OpenStation name, price class) of every station in PRICE_CLASSES."""
    stations = []
    for _, element in ET.iterparse(netex_path, events=("end",)):
        if element.tag != NETEX + "StopPlace":
            continue
        keys = {kv.findtext(NETEX + "Key"): kv.findtext(NETEX + "Value")
                for kv in element.findall(f"{NETEX}keyList/{NETEX}KeyValue")}
        price_class = keys.get("DBINFRAGO_PRICE_CATEGORY")
        parent = element.find(NETEX + "ParentSiteRef")
        ref = parent.get("ref") if parent is not None else ""
        if price_class in PRICE_CLASSES and ref.startswith("dhid:"):
            name = " ".join((element.findtext(NETEX + "Name") or "").split())
            stations.append((dhid_key(ref[5:]), name, int(price_class)))
        element.clear()
    return stations


def swift_string(text):
    return json.dumps(text, ensure_ascii=False)


def main(netex_path):
    names = {row[0]: row[1] for row in json.loads(NAMES.read_text())["germany"]}
    stations = big_stations(netex_path)
    missing = [name for dhid, name, _ in stations if dhid not in names]
    if missing:
        print(f"left out, not in StationNames.json (run make-station-names.py first): {missing}", file=sys.stderr)
    rows = sorted({(price, names[dhid], dhid) for dhid, _, price in stations if dhid in names})
    lines = [f"        BigStation(dhid: {swift_string(dhid)}, name: {swift_string(name)}, priceClass: {price}),"
             for price, name, dhid in rows]
    OUT.write_text(f"""// Generated by scripts/make-big-stations.py from DB InfraGO's OpenStation data (Deutsche Bahn AG, CC0 1.0).
// Don't edit by hand; rerun the script.

/// DB stations in price class 1 and 2 ("Preisklasse"), the big stations of the collection (#384).
public enum BigStations {{
    public static let all: [BigStation] = [
{chr(10).join(lines)}
    ]
}}
""")
    print(f"{len(rows)} stations → {OUT}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "netex.xml")
