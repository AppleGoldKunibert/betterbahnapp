# --- Names and numbers -------------------------------------------------------------------------------

def normalize_track(text):
    """The track number the app compares platforms by: "7 D-G" -> "7", "Gleis 4a" -> "4a", "07" -> "7",
    "Regio 3" -> "3" (Frankfurt Flughafen names its tracks so, in OSM and in the feeds). Must match
    `ExitSides.normalizedTrack` in the Kit. None when there is no number."""
    match = re.match(r"[^\d]*(\d+)([a-z])?(?![a-z0-9])", text.strip().lower())
    if not match:
        return None
    return (match.group(1).lstrip("0") or "0") + (match.group(2) or "")


def platform_refs(tags):
    """The track numbers a platform's `ref` (or `local_ref`) names: "7;8", "7/8", "7-8", "Gleis 7 und 8"."""
    for key in ("ref", "local_ref"):
        value = tags.get(key)
        if not value:
            continue
        refs = []
        for token in re.split(r"\s*(?:[;,/+&|]|\bund\b|\band\b)\s*", value):
            token = token.strip()
            span = re.fullmatch(r"(\d+)\s*[-–]\s*(\d+)", token)
            if span:
                # "7-8" names two tracks; "1-20" is a long span, not a list.
                if 0 < int(span.group(2)) - int(span.group(1)) <= 3:
                    refs.extend(str(n) for n in range(int(span.group(1)), int(span.group(2)) + 1))
            elif token:
                normalized = normalize_track(token)
                if normalized:
                    refs.append(normalized)
        if refs:
            return list(dict.fromkeys(refs))
    return []


def track_refs(tags):
    value = tags.get("railway:track_ref", "")
    return [n for n in (normalize_track(t) for t in re.split(r"[;,/]", value)) if n]


# --- Geometry ----------------------------------------------------------------------------------------

class Frame:
    """Flat metres around a reference point (fine within a few kilometres)."""

    def __init__(self, lat, lon):
        self.lat, self.lon = lat, lon
        self.kx = 111_320 * math.cos(math.radians(lat))
        self.ky = 110_540

    def xy(self, point):
        return ((point["lon"] - self.lon) * self.kx, (point["lat"] - self.lat) * self.ky)


def heading_of(dx, dy):
    """Compass bearing of a direction in flat metres (x east, y north)."""
    return math.degrees(math.atan2(dx, dy)) % 360


def mean_heading(headings):
    x = sum(math.sin(math.radians(h)) for h in headings)
    y = sum(math.cos(math.radians(h)) for h in headings)
    return heading_of(x, y) if (x or y) else None


def heading_difference(a, b):
    return abs((a - b + 180) % 360 - 180)


def project(point, line):
    """Nearest point of the polyline to `point`: (distance, segment index, side sign (+ left of the
    segment's direction, - right), the segment's heading)."""
    px, py = point
    best = None
    for i in range(len(line) - 1):
        (ax, ay), (bx, by) = line[i], line[i + 1]
        dx, dy = bx - ax, by - ay
        length2 = dx * dx + dy * dy
        if length2 == 0:
            continue
        t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / length2))
        qx, qy = ax + t * dx, ay + t * dy
        distance = math.hypot(px - qx, py - qy)
        if best is None or distance < best[0]:
            cross = dx * (py - ay) - dy * (px - ax)
            best = (distance, i, 1 if cross > 0 else -1, heading_of(dx, dy))
    return best


def densify(points, step=10.0, closed=False):
    """Points along the outline every `step` metres, so a platform drawn with four corners still has
    points all along its edge next to the track."""
    if len(points) < 2:
        return list(points)
    pairs = list(zip(points, points[1:] + (points[:1] if closed else [])))
    result = []
    for (ax, ay), (bx, by) in pairs:
        length = math.hypot(bx - ax, by - ay)
        count = max(1, int(length // step))
        result.extend((ax + (bx - ax) * k / count, ay + (by - ay) * k / count) for k in range(count))
    result.append(points[-1])
    return result


def platform_side(outline, track, edge=EDGE_DISTANCE):
    """Which side of `track` (a polyline in the way's node order) the platform `outline` (points in
    metres) lies on: ("left"/"right", heading of the track there), or None when the platform doesn't
    stand next to the track (nearer than `edge`) or straddles it (then the ref matched the wrong track)."""
    projections = [project(p, track) for p in outline]
    projections = [p for p in projections if p and p[0] <= SIDE_DISTANCE]
    if not projections or min(p[0] for p in projections) > edge:
        return None
    lefts = [p for p in projections if p[2] > 0]
    rights = [p for p in projections if p[2] < 0]
    if min(len(lefts), len(rights)) > 0.1 * len(projections):
        return None
    side_points = lefts if len(lefts) > len(rights) else rights
    return ("left" if side_points is lefts else "right", mean_heading([p[3] for p in side_points]))


def combine(findings):
    """One (side, heading) from the findings along several way pieces of the same track, all turned to
    the first piece's direction; None when they contradict each other."""
    if not findings:
        return None
    side0, heading0 = findings[0]
    sides, headings = [], []
    for side, heading in findings:
        if heading_difference(heading, heading0) > 90:
            side = "left" if side == "right" else "right"
            heading = (heading + 180) % 360
        sides.append(side)
        headings.append(heading)
    if len(set(sides)) > 1:
        return None
    return sides[0], mean_heading(headings)


# --- OSM data ----------------------------------------------------------------------------------------

def cells(bounds, margin=0.0):
    """The grid cells a bounding box touches, grown by `margin` degrees."""
    for i in range(math.floor((bounds["minlat"] - margin) / CELL_LAT), math.floor((bounds["maxlat"] + margin) / CELL_LAT) + 1):
        for j in range(math.floor((bounds["minlon"] - margin) / CELL_LON), math.floor((bounds["maxlon"] + margin) / CELL_LON) + 1):
            yield (i, j)


def bounds_of(points):
    return {"minlat": min(p["lat"] for p in points), "maxlat": max(p["lat"] for p in points),
            "minlon": min(p["lon"] for p in points), "maxlon": max(p["lon"] for p in points)}


class Data:
    """One tile's (or everything's) elements, indexed."""

    def __init__(self, elements):
        self.platforms = []   # (tags, [[{lat, lon}]] outlines, closed)
        self.rails = {}       # way id -> element, every railway=rail/light_rail way with geometry
        self.buffer_stops = set()
        self.stations = []
        self.ways_at_node = defaultdict(list)
        self.cells = defaultdict(list)
        for element in elements:
            tags = element.get("tags", {})
            kind = element["type"]
            if kind == "node":
                if tags.get("railway") == "buffer_stop":
                    self.buffer_stops.add(element["id"])
                elif tags.get("railway") in ("station", "halt") and tags.get("name") \
                        and tags.get("station") not in NOT_A_TRAIN_STATION and tags.get("subway") != "yes":
                    self.stations.append(element)
            elif kind == "way" and tags.get("railway") in ("rail", "light_rail") and len(element.get("geometry", [])) >= 2:
                if "bounds" not in element:
                    element["bounds"] = bounds_of(element["geometry"])
                self.rails[element["id"]] = element
                for node in (element["nodes"][0], element["nodes"][-1]):
                    self.ways_at_node[node].append(element["id"])
                for cell in cells(element["bounds"]):
                    self.cells[cell].append(element["id"])
            elif kind == "way" and tags.get("railway") in ("platform", "platform_edge") and len(element.get("geometry", [])) >= 2:
                closed = tags.get("railway") == "platform" and element["nodes"][0] == element["nodes"][-1]
                self.platforms.append((tags, [element["geometry"]], closed))
            elif kind == "relation" and tags.get("railway") == "platform":
                outlines = [m["geometry"] for m in element.get("members", [])
                            if m["type"] == "way" and m.get("role") in ("outer", "") and len(m.get("geometry", [])) >= 2]
                if outlines:
                    self.platforms.append((tags, outlines, True))

    def adjacent_tracks(self, outline, frame, bounds, edge, tags):
        """The tracks the platform `outline` (metres in `frame`, `tags`) stands next to, on its level:
        (way, side, heading)."""
        found = []
        xs, ys = [x for x, _ in outline], [y for _, y in outline]
        box = (min(xs) - SIDE_DISTANCE, min(ys) - SIDE_DISTANCE, max(xs) + SIDE_DISTANCE, max(ys) + SIDE_DISTANCE)
        seen = set()
        # The neighbouring cells too: a track right next to the platform can lie across a cell's edge.
        for cell in cells(bounds, margin=0.001):
            for way_id in self.cells.get(cell, []):
                if way_id in seen:
                    continue
                seen.add(way_id)
                track = self.rails[way_id]
                if not same_level(tags, track["tags"]):
                    continue
                line = [frame.xy(p) for p in track["geometry"]]
                # Only a track passing through the platform's surroundings can be its track.
                if not any(box[0] <= x <= box[2] and box[1] <= y <= box[3] for x, y in densify(line, 10.0)):
                    continue
                result = platform_side(outline, line, edge)
                if result:
                    found.append((track, result[0], result[1]))
        return found

    def dead_end_ahead(self, way, forward):
        """True when following the track from `way`'s end (or start) reaches a buffer stop without
        branching, within DEAD_END_WALK metres."""
        walked, current, seen = 0.0, way, {way["id"]}
        while True:
            node = current["nodes"][-1] if forward else current["nodes"][0]
            if node in self.buffer_stops:
                return True
            nexts = [w for w in self.ways_at_node[node] if w not in seen]
            if len(nexts) != 1:
                return False
            current = self.rails[nexts[0]]
            seen.add(current["id"])
            frame = Frame(current["geometry"][0]["lat"], current["geometry"][0]["lon"])
            line = [frame.xy(p) for p in current["geometry"]]
            walked += sum(math.dist(a, b) for a, b in zip(line, line[1:]))
            if walked > DEAD_END_WALK:
                return False
            # Continue away from the node we came in through.
            forward = current["nodes"][0] == node


def centroid(outlines):
    points = [p for outline in outlines for p in outline]
    return sum(p["lat"] for p in points) / len(points), sum(p["lon"] for p in points) / len(points)


def is_light_rail(station):
    """An S-Bahn (Berlin, Hamburg) or Stadtbahn station node, as OSM tags them."""
    return station["tags"].get("station") == "light_rail"


def nearest_station(data, lat, lon):
    frame = Frame(lat, lon)
    best = None
    for station in data.stations:
        if abs(station["lat"] - lat) > 0.01 or abs(station["lon"] - lon) > 0.016:
            continue
        distance = math.hypot(*frame.xy(station))
        if distance > STATION_DISTANCE:
            continue
        # A station with a code (DB's Ril100) beats a slightly nearer node without one, and the railway's
        # node beats the S-Bahn's own node of the same station (Berlin Hbf has four).
        rank = distance - (100 if station["tags"].get("railway:ref") else 0) + (300 if is_light_rail(station) else 0)
        if best is None or rank < best[0]:
            best = (rank, station)
    return best[1] if best else None


def level_of(tags):
    """An object's level, by `level`, else `layer`; None when it says nothing."""
    return tags.get("level", tags.get("layer"))


def same_level(a, b):
    """Whether two objects can lie on the same level: by `level`, else `layer`; one saying nothing fits
    any level. Berlin Hbf's upper platforms lie right above its lower tracks, in the map's two dimensions."""
    x, y = level_of(a), level_of(b)
    return x is None or y is None or x == y


def on_platform_level(platform_tags, candidates):
    """The candidates on the platform's level when they span several: the platform's own level, or
    the ground (no `level`/`layer`) for a platform that says nothing – Frankfurt Hbf's hall platforms
    lie above the S-Bahn's tunnel tracks. Empty when none is there: which level is it on, then?"""
    if len({level_of(a[0]["tags"]) for a in candidates}) <= 1:
        return candidates
    wanted = level_of(platform_tags) or "0"
    return [a for a in candidates if (level_of(a[0]["tags"]) or "0") == wanted]


def tracks_for(ref, refs, adjacent, is_edge, platform_tags={}):
    """Which of the `adjacent` tracks (way, side, heading) is platform `ref`'s: the ones numbered like
    it (`railway:track_ref`), else – for a platform edge, or a platform with one number – the only
    track next to it, possibly in several way pieces lying end to end (stations often number their
    tracks operationally, 101 for platform 1). Empty when that is ambiguous: tracks on both sides of a
    platform with one number, or two tracks at a platform "7;8" with other numbers."""
    numbered = [a for a in adjacent if ref in track_refs(a[0]["tags"])]
    if numbered:
        return numbered
    if not (is_edge or len(refs) == 1):
        return []
    # Pieces of one track all lie on the same side of the platform; a track numbered as another of
    # the platform's own tracks is that one, not this one.
    candidates = on_platform_level(platform_tags, [a for a in adjacent if not any(r in refs for r in track_refs(a[0]["tags"]))])
    if candidates and combine([(side, heading) for _, side, heading in candidates]) is not None:
        return candidates
    return []


def analyse(data, only=None, log=lambda *a: None):
    """{station node id: {"station": element, "tracks": {ref: (side, heading, terminal)}}}, plus the
    number of platform-track pairs dropped as contradictory."""
    stations = {}
    dropped = 0
    for tags, outlines, closed in data.platforms:
        refs = platform_refs(tags)
        if not refs:
            continue
        lat, lon = centroid(outlines)
        frame = Frame(lat, lon)
        outline = [q for o in outlines for q in densify([frame.xy(p) for p in o], closed=closed)]
        station = nearest_station(data, lat, lon)
        if station is None:
            continue
        name = station["tags"]["name"]
        if only and only.lower() not in name.lower():
            continue
        is_edge = tags.get("railway") == "platform_edge"
        edge = EDGE_DISTANCE if closed or is_edge else LINE_DISTANCE
        adjacent = data.adjacent_tracks(outline, frame, bounds_of([p for o in outlines for p in o]), edge, tags)
        for ref in refs:
            pieces = tracks_for(ref, refs, adjacent, is_edge, tags)
            if not pieces:
                continue
            combined = combine([(side, heading) for _, side, heading in pieces])
            if combined is None:
                log(f"  {name} Gleis {ref}: pieces disagree, dropped")
                dropped += 1
                continue
            side, heading = combined
            terminal = False
            for track, _, piece_heading in pieces:
                same_way = heading_difference(piece_heading, heading) <= 90
                if data.dead_end_ahead(track, forward=same_way):
                    terminal = True
                elif data.dead_end_ahead(track, forward=not same_way):
                    terminal = True
                    heading = (heading + 180) % 360
                    side = "left" if side == "right" else "right"
                if terminal:
                    break
            entry = stations.setdefault(station["id"], {"station": station, "tracks": {}})
            previous = entry["tracks"].get(ref)
            if previous is not None and previous != "conflict":
                p_side, p_heading, _ = previous
                flipped = ("left" if p_side == "right" else "right") if heading_difference(p_heading, heading) > 90 else p_side
                if flipped != side:
                    log(f"  {name} Gleis {ref}: two platforms on different sides, dropped")
                    entry["tracks"][ref] = "conflict"
                    dropped += 1
                    continue
                if not terminal:
                    continue  # keep the terminal finding
            if previous != "conflict":
                entry["tracks"][ref] = (side, heading, terminal)
    return stations, dropped


def track_sort_key(ref):
    match = re.match(r"(\d+)(.*)", ref)
    return (int(match.group(1)), match.group(2)) if match else (10 ** 6, ref)


def output(stations):
    rows = []
    for entry in stations.values():
        tags = entry["station"]["tags"]
        tracks = []
        for ref, finding in sorted(entry["tracks"].items(), key=lambda kv: track_sort_key(kv[0])):
            if finding == "conflict":
                continue
            side, heading, terminal = finding
            track = {"track": ref, "heading": int(round(heading)) % 360, "side": side}
            if terminal:
                track["terminal"] = True
            tracks.append(track)
        if not tracks:
            continue
        row = {"name": tags["name"]}
        if tags.get("railway:ref"):
            row["ril100"] = tags["railway:ref"]
        if re.fullmatch(r"\d{7}", tags.get("uic_ref", "")):
            row["uic"] = tags["uic_ref"]
        if is_light_rail(entry["station"]):
            # The app uses it for S-Bahn trains only: a Stadtbahn stop next to a station could share numbers.
            row["light"] = True
        row["lat"] = round(entry["station"]["lat"], 4)
        row["lon"] = round(entry["station"]["lon"], 4)
        row["tracks"] = tracks
        rows.append(row)
    rows.sort(key=lambda r: (r["name"], r["lat"]))
    return {"about": ABOUT, "stations": rows}


def dump(result):
    """One station per line, so diffs stay readable."""
    lines = [json.dumps(row, ensure_ascii=False, separators=(",", ":")) for row in result["stations"]]
    return '{"about":' + json.dumps(result["about"]) + ',\n"stations":[' + "".join("\n" + l + ("," if i < len(lines) - 1 else "") for i, l in enumerate(lines)) + "\n]}\n"


