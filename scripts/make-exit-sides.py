def tiles(bounds=BOUNDS, count=TILES):
    lat1, lon1, lat2, lon2 = bounds
    for i in range(count):
        for j in range(count):
            yield (round(lat1 + (lat2 - lat1) * i / count, 3), round(lon1 + (lon2 - lon1) * j / count, 3),
                   round(lat1 + (lat2 - lat1) * (i + 1) / count, 3), round(lon1 + (lon2 - lon1) * (j + 1) / count, 3))


def fetch(bbox, cache):
    path = cache / ("tile_%s_%s_%s_%s.json" % bbox) if cache else None
    if path and path.exists():
        with path.open() as file:
            return json.load(file)["elements"]
    query = QUERY.format(bbox=",".join(str(v) for v in bbox))
    body = urllib.parse.urlencode({"data": query}).encode()
    for attempt in range(6):
        url = OVERPASS[attempt % len(OVERPASS)]
        request = urllib.request.Request(url, data=body, headers={"User-Agent": "BetterBahn exit sides (github.com/AppleGoldKunibert/betterbahnapp)"})
        try:
            with urllib.request.urlopen(request, timeout=1000) as response:
                raw = response.read()
            result = json.loads(raw)
            if "remark" in result and "runtime error" in result["remark"]:
                raise urllib.error.URLError(result["remark"])
            if path:
                path.write_bytes(raw)
            return result["elements"]
        except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as error:
            print(f"  {url}: {error}, retrying in {15 * 2 ** attempt} s", file=sys.stderr)
            time.sleep(15 * 2 ** attempt)
    raise SystemExit(f"Overpass failed for {bbox}: try again later (finished tiles are cached), or smaller tiles (--tiles 12)")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--pbf", type=Path, help="an OSM extract (.osm.pbf, e.g. Geofabrik's germany-latest) to read instead of asking Overpass")
    parser.add_argument("--cache", type=Path, default=Path("/tmp/osm-exit-sides"), help="where the raw Overpass answers are kept")
    parser.add_argument("--only", help="only stations whose name contains this (debugging; nothing is written)")
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--tiles", type=int, default=TILES, help="tiles per side (default %(default)s)")
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)

    log = print if args.only else (lambda *a: None)
    stations, dropped = {}, 0
    if args.pbf:
        print(f"reading {args.pbf}", file=sys.stderr)
        elements = load_pbf(args.pbf)
        print(f"{len(elements)} railway elements", file=sys.stderr)
        stations, dropped = analyse(Data(elements), only=args.only, log=log)
    all_tiles = [] if args.pbf else list(tiles(count=args.tiles))
    for index, bbox in enumerate(all_tiles, 1):
        print(f"tile {index}/{len(all_tiles)} {bbox}", file=sys.stderr)
        elements = fetch(bbox, args.cache)
        found, lost = analyse(Data(elements), only=args.only, log=log)
        dropped += lost
        for station_id, entry in found.items():
            # A station node near a tile's edge can get platforms from two tiles.
            merged = stations.setdefault(station_id, {"station": entry["station"], "tracks": {}})
            merged["tracks"].update(entry["tracks"])
        time.sleep(2)

    result = output(stations)
    tracks = sum(len(s["tracks"]) for s in result["stations"])
    print(f"{len(result['stations'])} stations, {tracks} tracks, {dropped} dropped as contradictory", file=sys.stderr)
    if args.only:
        print(dump(result))
        return
    args.out.write_text(dump(result), encoding="utf-8")
    print(f"wrote {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
