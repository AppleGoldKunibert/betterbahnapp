def load_pbf(path):
    """The elements the analysis needs from an OSM extract, in Overpass' shape (tags, node ids, geometry,
    relation members with geometry). Four passes with pyosmium's C++ filters, so a country-sized file
    needs little memory and no Python work per node: the railway objects (every track's node ids, as a
    compact array), the member ways of platform relations, the positions of the platforms' nodes and
    every eighth node of the tracks, then all nodes of the tracks that pass a platform."""
    import osmium
    from array import array

    nodes, platforms, rails, relations, member_ways = [], {}, {}, [], set()
    for item in osmium.FileProcessor(str(path)).with_filter(osmium.filter.KeyFilter("railway")):
        railway = item.tags.get("railway")
        if item.is_node():
            if railway in ("buffer_stop", "station", "halt"):
                nodes.append({"type": "node", "id": item.id, "lat": item.location.lat, "lon": item.location.lon, "tags": dict(item.tags)})
        elif item.is_way():
            if railway in ("rail", "light_rail"):
                rails[item.id] = ({key: item.tags[key] for key in ("railway", "railway:track_ref", "layer", "level") if key in item.tags},
                                  array("q", (n.ref for n in item.nodes)))
            elif railway in ("platform", "platform_edge"):
                platforms[item.id] = {"type": "way", "id": item.id, "tags": dict(item.tags), "nodes": [n.ref for n in item.nodes]}
        elif item.is_relation() and railway == "platform":
            members = [(m.ref, m.role) for m in item.members if m.type == "w" and m.role in ("outer", "")]
            relations.append({"type": "relation", "id": item.id, "tags": dict(item.tags), "member_ids": members})
            member_ways.update(ref for ref, _ in members)
    missing = member_ways - platforms.keys()
    if missing:
        for item in osmium.FileProcessor(str(path), osmium.osm.WAY).with_filter(osmium.filter.IdFilter(missing)):
            platforms[item.id] = {"type": "way", "id": item.id, "tags": {}, "nodes": [n.ref for n in item.nodes], "member_only": True}

    # Every eighth node of each track and both ends: enough to see whether it passes a platform.
    wanted = {ref for way in platforms.values() for ref in way["nodes"]}
    for _, refs in rails.values():
        wanted.update(refs[::8])
        if len(refs):
            wanted.add(refs[-1])
    locations = {}
    for item in osmium.FileProcessor(str(path), osmium.osm.NODE).with_filter(osmium.filter.IdFilter(wanted)):
        locations[item.id] = {"lat": item.location.lat, "lon": item.location.lon}

    # Tracks far from every platform are not needed; near is by the cell grid of the platforms' nodes.
    reach_lat, reach_lon = TRACK_REACH / 110_540, TRACK_REACH / 70_000
    platform_cells = set()
    for way in platforms.values():
        for ref in way["nodes"]:
            if ref in locations:
                platform_cells.add((int(locations[ref]["lat"] // reach_lat), int(locations[ref]["lon"] // reach_lon)))
    def near_platform(location):
        i, j = int(location["lat"] // reach_lat), int(location["lon"] // reach_lon)
        return any((i + di, j + dj) in platform_cells for di in (-1, 0, 1) for dj in (-1, 0, 1))
    near_rails = {way_id for way_id, (_, refs) in rails.items() if len(refs) >= 2
                  and any(ref in locations and near_platform(locations[ref]) for ref in (*refs[::8], refs[-1]))}
    wanted = {ref for way_id in near_rails for ref in rails[way_id][1]} - locations.keys()
    for item in osmium.FileProcessor(str(path), osmium.osm.NODE).with_filter(osmium.filter.IdFilter(wanted)):
        locations[item.id] = {"lat": item.location.lat, "lon": item.location.lon}

    elements = list(nodes)
    for way_id in near_rails:
        tags, refs = rails[way_id]
        geometry = [locations[ref] for ref in refs if ref in locations]
        if len(geometry) >= 2:
            elements.append({"type": "way", "id": way_id, "tags": tags, "nodes": list(refs), "geometry": geometry})
    for way in platforms.values():
        geometry = [locations[ref] for ref in way["nodes"] if ref in locations]
        if len(geometry) < 2:
            continue
        way["geometry"] = geometry
        if not way.pop("member_only", False):
            elements.append(way)
    for relation in relations:
        relation["members"] = [{"type": "way", "ref": ref, "role": role, "geometry": platforms[ref]["geometry"]}
                               for ref, role in relation.pop("member_ids") if ref in platforms and "geometry" in platforms[ref]]
        elements.append(relation)
    return elements


