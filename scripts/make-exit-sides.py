"""Builds BetterBahnKit's offline list of exit sides (ExitSides.json) from OpenStreetMap (#394).

For every platform in Germany whose track OSM knows – a `railway=platform_edge` with a `ref` lying
right next to a `railway=rail` way, or a `railway=platform` with a `ref` next to a track with the same
`railway:track_ref` (or the only track next to it) – the side of the track the platform is on: "left" or "right" for a train travelling on `heading` (compass degrees, 0 = north,
90 = east). Coming the other way, the platform is on the other side; the app works the direction out
from the route's geometry or the previous stop. `terminal` marks a dead-end track (a buffer stop ahead
on `heading`): trains arriving there always travel on `heading`, so the side applies wherever they came
from. Platforms are assigned to the nearest station node, with its `railway:ref` (Ril100 code) and
`uic_ref` (EVA number) so the app can tell neighbouring stations apart.

The data (© OpenStreetMap contributors, ODbL) comes from an OSM extract read with pyosmium – the
reliable way, Overpass often answers 502/504 –, Germany from Geofabrik (about 4 GB, four passes over it):
    pip3 install osmium
    curl -O https://download.geofabrik.de/europe/germany-latest.osm.pbf
    python3 scripts/make-exit-sides.py --pbf germany-latest.osm.pbf [--only Fulda]
Without --pbf, Overpass is asked tile by tile; the raw answers are cached in --cache so a rerun doesn't
ask again. Corrections for wrong OSM data go into Resources/ExitSideOverrides.json (same format, by
hand), never into the generated file. Tests: python3 scripts/make-exit-sides-test.py
"""
